// Build both artifacts before publishing; --check only compares.
const fs = require('node:fs');
const path = require('node:path');
const root = __dirname;
const motion = {lookCode: "Look", graphicCode: "Graphic"};
const name = process.env.PANEL_NAME || "a16z Style Captions";
const localized = [
  ["de", "a16z-Stil-Untertitel"],
  ["en", "a16z Style Captions"],
  ["es", "Subt\u00edtulos estilo a16z"],
  ["fr", "Sous-titres style a16z"],
  ["it", "Sottotitoli stile a16z"],
  ["ja", "a16z\u30b9\u30bf\u30a4\u30eb\u5b57\u5e55"],
  ["ko", "a16z Style Captions"],
  ["pt", "Legendas estilo a16z"],
  ["tr", "a16z Tarz\u0131 Altyaz\u0131lar"],
  ["zh", "a16z \u98ce\u683c\u5b57\u5e55"]
];
const banner =
  "// @name " + name + "\n" +
  (name.startsWith("__") ? "" : localized.map(([l, n]) => "// @name:" + l + " " + n).join("\n") + "\n") +
  "// @icon captions\n" +
  "// One click turns a talking-head Draft into a 9:16 Short in the a16z house style: tightened pauses, speaker framing, editorial captions with lockups and emphasis, keyword cards, a name tag and a music bed.";


async function main() {
  const args = process.argv.slice(2), checkOnly = args.includes('--check');
  const modules = args.filter(arg => arg !== '--check');
  if (modules.length > 1 || args.filter(arg => arg === '--check').length > 1 || modules.some(arg => arg.startsWith('--')))
    throw Error('Usage: node build.cjs [path/to/esbuild] [--check]');
  const esbuild = require(modules[0] || process.env.SELECTS_ESBUILD || process.env.ESBUILD ||
    (process.env.SELECTS_DEV_REPO ? path.join(process.env.SELECTS_DEV_REPO, 'node_modules/esbuild') : 'esbuild'));
  const panelOut = process.env.PANEL_OUT || path.join(root, 'panel.tsx');
  const rendererOut = path.join(root, 'src', 'renderers.ts');
  let generated = '// Generated by build.cjs from src/motion. Do not edit.\n';
  for (const [name, entry] of Object.entries(motion)) {
    const result = esbuild.buildSync({entryPoints:[path.join(root,'src','motion',entry+'.tsx')], bundle:true,
      write:false, format:'esm', platform:'browser', external:['react','remotion'], jsx:'transform',
      minify:true, legalComments:'none'});
    generated += 'export const '+name+' = '+JSON.stringify(result.outputFiles[0].text)+';\n';
  }
  const panel = await esbuild.build({entryPoints:[path.join(root,'src','Panel.tsx')], outfile:panelOut,
    write:false, bundle:true, format:'esm', platform:'browser', external:['react'], jsx:'transform', loader:{'.py':'text'},
    minify:false, legalComments:'none', banner:{js:banner},
    footer:{js:'// app-update-guard:start\n'+fs.readFileSync(path.join(root,'../../shared/app-update-guard.ts'),'utf8').trimEnd()+'\n// app-update-guard:end'},
    plugins:[{name:'generated-renderers',setup(build){
      build.onLoad({filter:/renderers\.ts$/}, args => path.resolve(args.path)===rendererOut
        ? {contents:generated,loader:'ts',resolveDir:path.dirname(rendererOut)} : undefined);
    }}]});
  const outputs = [[rendererOut,generated],[panelOut,panel.outputFiles[0].text]];
  if (checkOnly) {
    const stale = outputs.filter(([file,text]) => !fs.existsSync(file) || fs.readFileSync(file,'utf8')!==text);
    if (stale.length) throw Error('Generated panel artifacts are out of date: '+stale.map(([file])=>path.relative(root,file)).join(', '));
    console.log('Checked '+path.basename(root)+' panel and renderers.');
  } else {
    for (const [file,text] of outputs) fs.writeFileSync(file,text);
    console.log('Built '+panelOut+' ('+panel.outputFiles[0].contents.length+' bytes).');
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
