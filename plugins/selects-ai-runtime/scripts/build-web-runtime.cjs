#!/usr/bin/env node
'use strict';

// Builds web/runtime.mjs, the single-file module Selects' web host imports.
//
// web/runtime.source.mjs is an ordinary ES module that imports pure CommonJS
// libraries shared with the desktop worker. A browser loads the runtime from
// one verified file, so the build embeds those libraries verbatim in a small
// module table and replaces each `import name from '../lib/x.cjs';` line with
// `const name = requireShared('lib/x.cjs');`. Shared libraries may require
// each other with relative './y.cjs' paths; anything else (node:*, packages)
// is refused, because it could not run in a browser Worker.
//
// Usage: node scripts/build-web-runtime.cjs [--check]
//   --check  exit 1 when the committed web/runtime.mjs is not up to date.
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'web/runtime.source.mjs');
const OUTPUT = path.join(ROOT, 'web/runtime.mjs');
const IMPORT_LINE = /^import (\w+) from '\.\.\/(lib\/[\w-]+\.cjs)';$/gm;
const REQUIRE_CALL = /\brequire\s*\(\s*(['"])([^'"]*)\1\s*\)/g;

/** Every library reachable from `entries`, dependencies first. */
function collectLibraries(entries) {
  const ordered = [];
  const seen = new Set();
  const visit = (id) => {
    if (seen.has(id)) return;
    seen.add(id);
    const source = fs.readFileSync(path.join(ROOT, id), 'utf8');
    const calls = [...source.matchAll(REQUIRE_CALL)];
    if (/\brequire\s*\(/.test(source.replace(REQUIRE_CALL, '')))
      throw new Error(`${id} calls require() with a computed path`);
    for (const [, , specifier] of calls) {
      if (!/^\.\/[\w-]+\.cjs$/.test(specifier))
        throw new Error(`${id} requires ${specifier}; the web runtime can embed only sibling lib/*.cjs files`);
      visit(path.posix.join('lib', specifier.slice(2)));
    }
    ordered.push({ id, source });
  };
  entries.forEach(visit);
  return ordered;
}

function buildWebRuntime() {
  const source = fs.readFileSync(SOURCE, 'utf8');
  const imports = [...source.matchAll(IMPORT_LINE)].map(([, name, id]) => ({ name, id }));
  if (imports.length === 0) throw new Error('web/runtime.source.mjs imports no shared libraries');
  const body = source.replace(IMPORT_LINE, (_, name, id) => `const ${name} = requireShared(${JSON.stringify(id)});`);
  if (/^import\s/m.test(body)) throw new Error('web/runtime.source.mjs may import only ../lib/*.cjs default exports');
  const libraries = collectLibraries(imports.map(({ id }) => id));
  const table = libraries.map(({ id, source: library }) => [
    `  // --- ${id} (embedded verbatim) ---`,
    `  ${JSON.stringify(id)}: function (module, exports, require) {`,
    library.trimEnd(),
    '  },',
  ].join('\n'));
  return [
    '// GENERATED by scripts/build-web-runtime.cjs from web/runtime.source.mjs. Do not edit.',
    'const sharedLibraries = {',
    ...table,
    '};',
    'const sharedCache = new Map();',
    'function requireShared(id) {',
    '  if (!sharedCache.has(id)) {',
    '    const module = { exports: {} };',
    '    sharedCache.set(id, module);',
    "    const relative = (specifier) => requireShared('lib/' + specifier.slice(2));",
    '    sharedLibraries[id](module, module.exports, relative);',
    '  }',
    '  return sharedCache.get(id).exports;',
    '}',
    body,
  ].join('\n');
}

if (require.main === module) {
  const built = buildWebRuntime();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== built) {
      console.error('web/runtime.mjs is stale; run node scripts/build-web-runtime.cjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUTPUT, built);
  }
}

module.exports = { buildWebRuntime, OUTPUT };
