// The program from the measured narration lengths: narration starts, transition slots and scene spans. Sentences are
// separated by the scene pause; a ~1.8 s transition slot is centred in each pause (a short sentence narrows the slots
// either side so its scene keeps at least `minSpan` on screen). Scene i's clip plays from its first frame at 1.0x for
// its span, from the end of the slot before it to the start of the slot after it. Slot edges and the end sit on the
// Draft's frame grid, so every Main clip is a whole number of frames.
// Slot half-widths of the boundary types that are not generated clips: a 0.5 s dissolve, a 3-frame white flash, a cut.
const FIXED_HALF = { dissolve: 0.25, flash: 1.5 / MED_FPS, cut: 0 };
export function medTimeline(durs, types = null, t = MED_TIMING) {
  if (types && !Array.isArray(types)) { t = types; types = null; }
  const n = durs.length;
  if (!n) throw medFail("no narration");
  const narration = [];
  let at = t.lead;
  for (let i = 0; i < n; i++) {
    narration.push({ scene: i + 1, start: r3(at), dur: r3(durs[i]) });
    at += durs[i] + t.scenePause;
  }
  const last = narration[n - 1];
  const total = medFrame(last.start + last.dur + t.endHold);
  const room = (L) => (L + t.scenePause - t.minSpan) / 2;
  const boundaries = [];
  for (let i = 0; i + 1 < n; i++) {
    const center = narration[i].start + durs[i] + t.scenePause / 2;
    // Each boundary's type comes from the plan (default push: a generated transition clip in a ~1.8 s slot).
    const type = types && MED_TRANSITIONS.includes(types[i]) ? types[i] : "push";
    const generated = medGeneratedTransition(type);
    const half = generated ? Math.max(t.minHalf, Math.min(t.slot / 2, room(durs[i]), room(durs[i + 1]))) : FIXED_HALF[type];
    const start = medFrame(center - half), end = type === "cut" ? start : medFrame(center + half);
    boundaries.push({ after: i + 1, center: r3(center), type, generated, start, end, slot: medFrame(end - start) });
  }
  const scenes = durs.map((L, i) => {
    const start = i === 0 ? 0 : boundaries[i - 1].end;
    const end = i === n - 1 ? total : boundaries[i].start;
    const span = medFrame(end - start);
    return { n: i + 1, start, end, span, clipSeconds: Math.min(MED_KLING_MAX, Math.max(medSceneClipSeconds(L), Math.ceil(span - 1e-9))) };
  });
  return { total, narration, boundaries, scenes };
}
// Overlay windows inside one scene span. Every overlay that belongs to a scene (its label, pointer labels, split labels,
// insets) ends before the transition after it starts. Pointer labels show 1.5-2.5 s each, the second 0.5 s after the
// first; one that cannot get 1.5 s inside the span is left out.
export function medSceneWindows(scene, pointerCount) {
  const label = scene.end - 0.1 - (scene.start + 0.1) >= 0.5 ? { start: r3(scene.start + 0.1), end: r3(scene.end - 0.1) } : null;
  const pointers = [];
  for (let k = 0; k < pointerCount; k++) {
    const start = scene.start + 0.3 + 0.5 * k;
    const end = Math.min(start + 2.5, scene.end - 0.1);
    pointers.push(end - start >= 1.5 ? { start: r3(start), end: r3(end) } : null);
  }
  return { label, pointers };
}

