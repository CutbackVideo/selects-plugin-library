// The camera move of a generated transition: the plan's push or pull, a dive-in / pull-out when the zoom chain jumps
// two or more scale steps. Without a type (older plans) it follows the change of scale.
export function medTransitionMove(fromScale, toScale, type = null) {
  const d = MED_SCALES.indexOf(toScale) - MED_SCALES.indexOf(fromScale);
  if (type === "push") return d >= 2 ? "dive-in" : "push-in";
  if (type === "pull") return d <= -2 ? "pull-out" : "pull-back";
  if (d >= 2) return "dive-in";
  if (d <= -2) return "pull-out";
  if (d === -1) return "pull-back";
  return "push-in";
}
const MOVE_TEXT = {
  "dive-in": "a fast continuous dive-in: the camera flies forward and plunges deep toward the next, much closer view",
  "push-in": "a smooth continuous push-in: the camera moves forward into the subject",
  "pull-back": "a smooth continuous pull-back: the camera moves backward and the view widens",
  "pull-out": "a fast continuous pull-out: the camera flies backward to a much wider view",
};
export function medTransitionPrompt(from, to, art = "medical") {
  const move = medTransitionMove(from.scale, to.scale, medGeneratedTransition(from.transitionOut) ? from.transitionOut : null);
  return slice(`${(MED_ARTS[art] || MED_ARTS.medical).motion}. ONE continuous camera move, ${MOVE_TEXT[move]}, from the first frame to the last ` +
    `frame. Start: ${slice(from.subject || from.visual, 0, 400)}. End: ${slice(to.subject || to.visual, 0, 400)}. Seamless and fluid, no cut, no fade, no flash; ` +
    "keep every shape solid, no melting, no text, no labels.", 0, 2500);
}
