export function medExtractArticle(url, s) {
  const t = /<title>(.*?)<\/title>/s.exec(s);
  const art = { url, title: metaTag(s, "og:title") || stripTags(t ? t[1] : ""), description: metaTag(s, "og:description"),
    source: metaTag(s, "og:site_name"), date: metaTag(s, "article:published_time"), body: "", method: "" };
  const m = /Fusion\.globalContent\s*=\s*(\{.*?\});\s*Fusion\./s.exec(s); // Arc XP (Chosun and others)
  if (m) {
    let d = null;
    try { d = JSON.parse(m[1]); } catch { d = null; }
    const paras = (d && Array.isArray(d.content_elements) ? d.content_elements : []).filter((e) => asObj(e).type === "text").map((e) => stripTags(e.content || ""));
    if (paras.length) {
      art.body = paras.filter(Boolean).join("\n");
      art.title = asObj(d.headlines).basic || art.title;
      art.method = "arc";
    }
  }
  if (!art.body) {
    for (const bm of s.matchAll(/<script[^>]+application\/ld\+json[^>]*>(.*?)<\/script>/gs)) {
      let d;
      try { d = JSON.parse(strip(bm[1])); } catch { continue; }
      const items = Array.isArray(d) ? d : d && typeof d === "object" ? (d["@graph"] !== undefined ? d["@graph"] : [d]) : [];
      for (const it of Array.isArray(items) ? items : []) {
        if (!(it && typeof it === "object" && String(it["@type"] || "").includes("Article"))) continue;
        if (truthy(it.articleBody) && !art.body) { art.body = stripTags(it.articleBody); art.title = it.headline || art.title; art.method = "jsonld"; }
      }
    }
  }
  if (!art.body) {
    const sc = /<article[^>]*>(.*?)<\/article>/s.exec(s);
    const paras = [...(sc ? sc[1] : s).matchAll(/<p[^>]*>(.*?)<\/p>/gs)].map((x) => stripTags(x[1]));
    art.body = paras.filter((p) => medLen(p) > 40 && !/^(Share|Save|Advertisement|Related)\b/.test(p)).join("\n");
    art.method = "paragraphs";
  }
  art.body = slice(art.body, 0, 20000);
  art.lang = medDetectLang(art.title + " " + art.body);
  return art;
}
async function cmdFetch(io, job) {
  const inp = asObj(job.data.input);
  let art;
  if (inp.kind === "topic") {
    const topic = strip(inp.topic || "");
    if (medLen(topic) < 2) throw medFail("TEXT_TOO_SHORT");
    art = { url: "", title: slice(topic, 0, 120), description: "", source: "", date: "", body: "", method: "topic", lang: medDetectLang(topic, true) };
  } else if (inp.kind === "text") {
    const text = strip(inp.text || "");
    if (medLen(text) < 80) throw medFail("TEXT_TOO_SHORT");
    const first = text.split(/\r?\n/).map(strip).filter(Boolean)[0] || "";
    art = { url: "", title: slice(first, 0, 120), description: "", source: "", date: "", body: slice(text, 0, 20000), method: "text", lang: medDetectLang(text) };
  } else {
    const url = strip(inp.url || "");
    let r;
    try { r = await io.http(url, MED_UA_BROWSER, 30); } catch (e) { throw medFail("FETCH_FAILED"); }
    if (r.code >= 300) throw medFail("FETCH_FAILED");
    art = medExtractArticle(url, r.text);
    if (medLen(art.body) < 200) throw medFail("NO_TEXT");
  }
  const want = settingsOf(job).lang;
  const lang = want && want !== "auto" && MED_LANG[want] ? want : MED_LANG[art.lang] ? art.lang : "ko";
  await io.writeJson(job.p("article.json"), art);
  Object.assign(job.data, { stage: "fetched", lang });
  await job.save();
  const L = MED_LANG[lang];
  return { ok: true, title: art.title, method: art.method, lang, language: L.name, style: L.style, budget: medBudget(lang), titleChars: L.title, labelChars: L.label };
}

