  // The AI picks one take (or candidate) per item from contact sheets, four sheets per question. An item with one
  // delivered option takes it; a failed question falls back to the first option.
  async function aiPick(dir: string, kind: "keyframes" | "clips" | "transitions", only: string[], describe: (n: number) => any) {
    if (!only.length) return;
    const field = kind === "keyframes" ? "kf" : kind === "clips" ? "clip" : "tr";
    const sh = await run("sheet", dir, [kind, only.join(",")], "Contact sheets");
    const picks = await readPicks(dir);
    const ask4 = sh.sheets.filter((s: any) => s.options.length > 1);
    for (const s of sh.sheets) if (s.options.length === 1) picks[field][String(s.scene)] = s.options[0];
    for (let i = 0; i < ask4.length; i += 4) {
      const part = ask4.slice(i, i + 4);
      let answer: any[] = [];
      try {
        const images = [];
        for (const s of part) images.push({ dataUrl: await sheetImage(s.path), name: String(s.scene) });
        answer = (await ask(pickPrompt(kind, part.map((s: any) => ({ scene: s.scene, options: s.options, ...describe(s.scene) }))), images)).picks || [];
      } catch (err) {
        answer = []; // the pick is advisory; the first option stands in
      }
      for (const s of part) {
        const a = answer.find((x: any) => String(x.scene) === String(s.scene));
        const pick = String(a?.pick || "").trim().toUpperCase();
        picks[field][String(s.scene)] = s.options.includes(pick) ? pick : kind === "transitions" && pick === "NONE" ? "none" : s.options[0];
      }
    }
    await writePicks(dir, picks);
  }

