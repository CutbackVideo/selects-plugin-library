// The job's gen map may be in two places (gen.json and plugin storage); keep each request's most advanced record.
function mergeGen(a: any, b: any): any {
  const out: any = { ...(a || {}) };
  for (const [k, v] of Object.entries(b || {}) as any) {
    const cur = out[k];
    const rank = (x: any) => (!x ? -1 : x.path ? 3 : x.jobId ? 2 : 1) + (x?.attempt || 1) * 10;
    if (!cur || rank(v) > rank(cur)) out[k] = v;
  }
  return out;
}
