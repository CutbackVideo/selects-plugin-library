async function cmdTimeline(io, job) {
  const plan = await job.plan();
  const lang = plan.lang;
  const durs = [], aligned = [];
  for (const s of plan.scenes) {
    const path = await job.file(`narr:${s.n}`);
    if (!path) throw medFail(`narration missing: scene ${s.n}`);
    const d = await io.duration(path);
    durs.push(d);
    aligned.push({ file: path, words: medAlignWords(s.narration, d, await io.silences(path), lang) });
  }
  const videoId = settingsOf(job).video;
  const tl = medApplyVideoModel(medTimeline(durs, medTransitionTypes(plan, videoId)), videoId);
  const L = MED_LANG[lang];
  const captions = [];
  plan.scenes.forEach((s, i) => {
    const nr = tl.narration[i];
    // The last caption of a sentence stays up through the pause (and any transition) until the next sentence's first
    // caption; the final one to the end of the Draft.
    const hold = i + 1 < plan.scenes.length ? tl.narration[i + 1].start : tl.total;
    captions.push(...medTimedCaptions(s.narration, aligned[i].words, nr.start, nr.dur, L.cap, hold));
  });
  // Music bills by started minute: stay under the boundary.
  const needS = tl.total + 1;
  const musicS = Math.min(Math.ceil(needS), 60 * Math.ceil(needS / 60.0) - 1);
  const out = { ...tl, files: aligned.map((a) => a.file), captions, music_ms: Math.trunc(musicS * 1000) };
  await io.writeJson(job.p("timeline.json"), out);
  job.data.stage = "timed";
  await job.save();
  let video = 0;
  for (const s of tl.scenes) video += s.clipSeconds;
  return { ok: true, seconds: tl.total, scenes: tl.scenes.length, videoSeconds: video, tooLong: medLengthProblems(tl, videoId) };
}

