const letter = (i) => MED_LETTERS[i];
// Selects accepts a requestKey of 8-64 characters from [A-Za-z0-9_-]. A key that already fits is used as it is (so
// existing jobs keep their keys); any other is made to fit: other characters become "_", and a stable hash of the
// original is appended (shortening the readable part if needed), so two different keys never collide.
export const MED_KEY_PATTERN = /^[A-Za-z0-9_-]{8,64}$/;
function fnv(str, seed) {
  let h = seed >>> 0;
  for (const ch of String(str)) { h ^= ch.codePointAt(0); h = Math.imul(h, 16777619) >>> 0; }
  return h.toString(36).padStart(7, "0");
}
export function medRequestKey(raw) {
  const s = String(raw);
  if (MED_KEY_PATTERN.test(s)) return s;
  const hash = fnv(s, 2166136261) + fnv(s, 3323198485);
  const head = s.replace(/[^A-Za-z0-9_-]/g, "_").slice(0, 64 - hash.length - 1);
  return `${head || "mx"}-${hash}`.padEnd(8, "0");
}
async function cmdRequests(io, job, kind, only, attempt) {
  const plan = await job.plan();
  const set = settingsOf(job);
  const reqs = [];
  const spec = (gen, tool, model, input, uploads, folder, extraKey = "") => ({
    key: medRequestKey(`${job.id}-${gen.replace(/:/g, "-")}-${attempt}${extraKey}`), gen, attempt, tool, modelId: MED_MODEL[model], input, uploads: uploads || {},
    outputName: `${job.id}_${gen.replace(/:/g, "_")}_${attempt}`, folder: io.join(job.dir, "gen", folder),
  });
  const want = (id) => !only || only.has(String(id));
  // Pictures follow the plan's mode, art and layout; a plan from an older version of this app is not continued.
  if (kind !== "narration" && kind !== "music" && plan.version !== MED_VERSION) throw medFail("OLD_PLAN");
  const style = medStyleFor(set, plan);
  if (kind === "narration") {
    for (const s of plan.scenes) if (want(s.n)) {
      const r = medNarrationInput(s.narration, set.voice, plan.lang);
      // An edited sentence (rev > 0) is a different request: its text is part of the key.
      reqs.push(spec(`narr:${s.n}`, "audio", r.model, r.input, null, "narration", s.rev ? `-v${s.rev}` : ""));
    }
  } else if (kind === "keyframes" || kind === "kfregen") {
    // Scene 1 is drawn from text; every later scene is an edit with scene 1's chosen keyframe as the style reference.
    // `kfregen`: the keyframe the user asked for, per scene, with the model they chose (picks.regen); never automatic.
    const picks = await job.picks();
    const regen = kind === "kfregen";
    for (const s of plan.scenes) {
      const ask = regen ? asObj(asObj(picks.regen)[String(s.n)]) : null;
      if (regen && !(ask.k >= 1)) continue;
      const modelId = regen ? (MED_KF_MODELS[ask.model] ? ask.model : set.kfModel) : set.kfModel;
      const model = medKfModel(modelId);
      const letters = regen ? [medRegenLetter(ask.k)] : Array.from(MED_LETTERS.slice(0, MED_KF_CANDIDATES));
      for (const c of letters) {
        const id = `${s.n}${c}`;
        if (only && !only.has(id) && !only.has(String(s.n))) continue;
        const gen = `kf:${s.n}:${c}`;
        const first = medFamilyFirst(plan, s);
        const styled = s.n > first && !!model.edit;
        const input = model.input(medKeyframePrompt(s, styled, medSceneSuffix(style, s)), style.geo.aspect);
        // The model's short tag (never its id, which may hold "."), so the key stays within the host's pattern.
        const key = regen || modelId !== MED_KF_DEFAULT ? `-m${model.tag}` : "";
        const make = (mid, inp, uploads, extra) => ({ ...spec(gen, "image", "t2i", inp, uploads, "keyframes", key + extra), modelId: mid });
        if (!styled) { reqs.push(make(model.t2i, input, null, "")); continue; }
        const ref = picks.kf[String(first)];
        const refPath = ref ? await job.file(`kf:${first}:${ref}`) : null;
        if (!refPath) throw medFail(`scene ${first} keyframe not chosen`);
        input.image_urls = ["selects-input:ref"];
        // Scene 1's family keeps its earlier key form; the other family names its reference scene.
        reqs.push(make(model.edit, input, { ref: refPath }, first === 1 ? `-r${ref}` : `-r${first}${ref}`));
      }
    }
  } else if (kind === "clips") {
    const tl = await job.timeline();
    const picks = await job.picks();
    for (const s of plan.scenes) {
      const pick = picks.kf[String(s.n)];
      const kf = pick ? await job.file(`kf:${s.n}:${pick}`) : null;
      if (!kf) throw medFail("keyframe not chosen: scene " + s.n);
      for (let t = 0; t < MED_TAKES; t++) {
        const id = `${s.n}${letter(t)}`;
        if (only && !only.has(id) && !only.has(String(s.n))) continue;
        const vr = medVideoRequest(set.video, set.quality, { prompt: medMotionPrompt(s, medSceneArt(style, s)), negative: NEGATIVE,
          seconds: tl.scenes[s.n - 1].clipSeconds, aspect: style.geo.aspect });
        reqs.push({ ...spec(`clip:${s.n}:${letter(t)}`, "video", "i2v", vr.input, { start: kf }, "clips", `-k${pick}${vr.tag}`), modelId: vr.modelId });
      }
    }
  } else if (kind === "transitions") {
    // Start: the last frame scene i shows; end: the first frame of scene i+1 (both written by `strips`).
    const picks = await job.picks();
    // Only push and pull boundaries are generated clips; cut, flash and dissolve are made locally.
    const types = medTransitionTypes(plan, set.video);
    for (const s of plan.scenes.slice(0, -1).filter((x, i) => medGeneratedTransition(types[i]))) {
      const next = plan.scenes[s.n];
      // The frames depend on both scenes' chosen clips; a different choice is a different request.
      const pair = `-c${picks.clip[String(s.n)] || "K"}${picks.clip[String(next.n)] || "K"}`;
      const start = job.p("work", `out_${s.n}.png`), end = job.p("work", `in_${next.n}.png`);
      if (!(await io.exists(start)) || !(await io.exists(end))) throw medFail("transition frames missing: " + s.n);
      for (let t = 0; t < MED_TAKES; t++) {
        const id = `${s.n}${letter(t)}`;
        if (only && !only.has(id) && !only.has(String(s.n))) continue;
        const vr = medVideoRequest(set.video, set.quality, { prompt: medTransitionPrompt(s, next, s.look === "inside" || next.look === "inside" ? "medical" : style.art),
          negative: NEGATIVE, seconds: medVideoModel(set.video).transitionSeconds, end: true, aspect: style.geo.aspect });
        reqs.push({ ...spec(`tr:${s.n}:${letter(t)}`, "video", "i2v", vr.input, { start, end }, "transitions", pair + vr.tag), modelId: vr.modelId });
      }
    }
  } else if (kind === "music") {
    const tl = await job.timeline();
    reqs.push(spec("music", "audio", "music", { prompt: MED_MUSIC_PROMPT, force_instrumental: true, music_length_ms: tl.music_ms }, null, "music"));
  } else {
    throw medFail("unknown request kind " + kind);
  }
  return { ok: true, requests: reqs };
}

