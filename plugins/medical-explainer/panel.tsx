// Speech weight of one word (syllables for CJK, vowel groups otherwise): the speech-length estimate and the word timing.
export function medWordWeight(w, lang) {
  const digits = (w.match(/\p{Nd}/gu) || []).length;
  if (MED_LANG[lang].cjk) {
    const cjk = (w.match(/[\uac00-\ud7a3\u3040-\u30ff\u4e00-\u9fff]/gu) || []).length;
    let lat = 0;
    for (const x of w.match(/[A-Za-z]+/g) || []) lat += x.length * (/^[A-Z]+$/.test(x) ? 1.5 : 0.5);
    return Math.max(0.5, cjk + digits * 1.5 + lat);
  }
  const groups = (w.match(/[aeiouy\u00e0-\u00e5\u00e8-\u00eb\u00ec-\u00ef\u00f2-\u00f6\u00f9-\u00fc\u0131AEIOUY]+/gu) || []).length;
  const bare = w.replace(/[^\p{L}\p{N}_]/gu, "");
  const caps = /^[A-Z]{2,5}$/.test(bare) ? medLen(w) : 0;
  return Math.max(1.0, groups, caps) + digits * 1.2;
}
