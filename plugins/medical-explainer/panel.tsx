// The AI's script as the plan the engine uses. The mode is the user's choice, else the script's, else zoom. Every scene
// has `subject` (what the picture shows) and `motion` (how it moves) from the script, and `transitionOut` (cut, flash,
// dissolve, push, pull). Mode overlay fields are kept for their mode only: myth `mythIndex` 1-3, `verdict` O/X and a
// one-line `reasonCard`; timeline `timeChip`; list `stepNumber` and `stepCard`. At most one split scene (left must be
// an earlier scene) and one inset scene (exactly two insets, from other scenes); texts are shortened to fit.
// `look`: "scene" (the job's art preset) or "inside" (3D medical CG inside the body). Zoom is all inside; the
// "Inside-the-body shots" setting "off" keeps every scene a scene. A boundary into or between inside scenes is a push
// and one out of them a pull (generated camera moves, as in zoom); other boundaries follow the mode.
export function medNormalizePlan(raw, lang, fallbackTitle, modeSetting = "auto", insideSetting = "auto") {
  const L = MED_LANG[lang] || MED_LANG.en;
  const warnings = [], errors = [];
  raw = asObj(raw);
  const mode = MED_MODES[modeSetting] ? modeSetting : MED_MODES[raw.mode] ? raw.mode : "zoom";
  const list = Array.isArray(raw.scenes) ? raw.scenes : [];
  const scenes = [];
  for (const s0 of list) {
    const s = asObj(s0);
    const narration = strip(String(s.narration || "").replace(/\s+/gu, " "));
    const visual = strip(String(s.subject || s.visual || s.visual_prompt || ""));
    if (!narration) continue;
    if (!visual) { errors.push(`scene ${scenes.length + 1} has no subject`); continue; }
    const label = slice(strip(s.label || ""), 0, L.label);
    const pointers = (Array.isArray(s.pointers) ? s.pointers : []).map((p) => slice(strip(typeof p === "string" ? p : asObj(p).label || ""), 0, L.label)).filter(Boolean).slice(0, 2);
    const subject = slice(visual, 0, 900);
    const sc = { n: scenes.length + 1, narration, subject, visual: subject, motion: slice(strip(s.motion || ""), 0, 300), camera: normCamera(s.camera),
      scale: normScale(s.scale), transitionOut: strip(s.transitionOut || s.transition || "").toLowerCase(),
      look: mode === "zoom" ? "inside" : insideSetting !== "off" && strip(s.look || "").toLowerCase() === "inside" ? "inside" : "scene", label, pointers, split: null, insets: null, _split: s.split, _insets: s.insets };
    if (mode === "myth") {
      const verdict = VERDICT[strip(String(s.verdict ?? "")).toLowerCase()] || null;
      if (verdict) Object.assign(sc, { verdict, mythIndex: parseInt(s.mythIndex, 10) || 0, reasonCard: slice(strip(s.reasonCard || ""), 0, L.cap + 4) });
    } else if (mode === "timeline") {
      const chip = slice(strip(s.timeChip || ""), 0, 10);
      if (chip) sc.timeChip = chip;
    } else if (mode === "list") {
      const step = parseInt(s.stepNumber, 10);
      if (step >= 1) Object.assign(sc, { stepNumber: step, stepCard: slice(strip(s.stepCard || ""), 0, L.cap + 4) });
    }
    scenes.push(sc);
  }
  if (scenes.length < 3) errors.push("fewer than 3 scenes");
  if (scenes.length && (scenes.length < 8 || scenes.length > 10)) warnings.push(`${scenes.length} sentences (8-10 expected)`);
  let split = false, insets = false;
  for (const s of scenes) {
    const sp = asObj(s._split);
    const left = parseInt(sp.left !== undefined ? sp.left : sp.sceneRef, 10);
    if (truthy(s._split)) {
      if (split) warnings.push(`scene ${s.n}: only one split scene is kept`);
      else if (!(left >= 1 && left < s.n)) warnings.push(`scene ${s.n}: split left must be an earlier scene`);
      else { s.split = { left, leftLabel: slice(strip(sp.leftLabel || ""), 0, L.label), rightLabel: slice(strip(sp.rightLabel || ""), 0, L.label) }; split = true; }
    }
    const ins = (Array.isArray(s._insets) ? s._insets : []).map(asObj).map((x) => ({ sourceScene: parseInt(x.sourceScene !== undefined ? x.sourceScene : x.scene, 10), label: slice(strip(x.label || ""), 0, L.label) }))
      .filter((x) => x.sourceScene >= 1 && x.sourceScene <= scenes.length && x.sourceScene !== s.n);
    if (truthy(s._insets)) {
      if (insets) warnings.push(`scene ${s.n}: only one inset scene is kept`);
      else if (ins.length < 2) warnings.push(`scene ${s.n}: insets need two other scenes`);
      else if (s.split) warnings.push(`scene ${s.n}: a split scene has no insets`);
      else { s.insets = ins.slice(0, 2); insets = true; }
    }
    delete s._split;
    delete s._insets;
  }
  scenes.forEach((s, i) => {
    const next = scenes[i + 1];
    if (!next) { s.transitionOut = null; return; }
    s.transitionOut = mode !== "zoom" && next.look === "inside" ? "push" : mode !== "zoom" && s.look === "inside" ? "pull"
      : normTransition(s.transitionOut, mode, s.scale, next.scale);
  });
  if (mode === "myth") {
    // At most three myths, numbered in order.
    let k = 0;
    for (const s of scenes) if (s.verdict) { if (k >= 3) { delete s.verdict; delete s.mythIndex; delete s.reasonCard; } else s.mythIndex = ++k; }
    if (k < 2) warnings.push(`${k} myth(s) judged (2-3 expected)`);
  }
  if (mode === "list" && !scenes.some((s) => s.stepNumber)) warnings.push("no numbered steps");
  if (mode === "timeline" && !scenes.some((s) => s.timeChip)) warnings.push("no time markers");
  const tl = (Array.isArray(raw.title_lines) ? raw.title_lines : []).map((x) => slice(strip(x), 0, L.title * 2)).filter(Boolean);
  if (!tl.length) tl.push(...medCaptionLines(slice(strip(fallbackTitle || ""), 0, L.title * 2), L.title).slice(0, 2));
  return { plan: { version: MED_VERSION, lang, mode, title: [tl[0] || "", tl[1] || ""], reviewNote: slice(strip(raw.review_note || ""), 0, 400), scenes }, warnings, errors };
}
export function medEstimateSeconds(plan) {
  let s = MED_TIMING.lead + MED_TIMING.endHold + Math.max(0, plan.scenes.length - 1) * MED_TIMING.scenePause;
  for (const sc of plan.scenes) s += medSpeechSeconds(sc.narration, plan.lang);
  return Math.round(s * 10) / 10;
}
// What one full run generates (before narration lengths are known the scene lengths are estimated from the text).
export function medGenerationCounts(plan, music, videoId = MED_VIDEO_DEFAULT) {
  const n = plan.scenes.length;
  const v = medVideoModel(videoId);
  let clipSeconds = 0;
  for (const sc of plan.scenes) {
    const need = medSceneClipSeconds(medSpeechSeconds(sc.narration, plan.lang));
    clipSeconds += (medVideoSeconds(videoId, need) ?? v.durations[v.durations.length - 1]) * MED_TAKES;
  }
  // Only push/pull boundaries are generated clips, and only with a model that takes an end frame; the others dissolve.
  const types = medTransitionTypes(plan, videoId);
  const generated = types.filter(medGeneratedTransition).length;
  const fallback = plan.scenes.slice(0, -1).filter((s, i) => medGeneratedTransition(s.transitionOut || "push") && !medGeneratedTransition(types[i])).length;
  return { images: n * MED_KF_CANDIDATES, clips: n * MED_TAKES, clipSeconds: clipSeconds + generated * MED_TAKES * v.transitionSeconds,
    transitions: generated * MED_TAKES, dissolveFallback: fallback, narrations: n, music: !!music };
}

