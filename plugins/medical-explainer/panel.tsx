export function medNarrationInput(text, voiceId, lang) {
  const v = MED_VOICES.find((x) => x.id === voiceId) || MED_VOICES[0];
  if (v.model === "minimax") {
    // output_format "url": the default ("hex") returns audio inside the JSON instead of a file.
    return { model: "minimax", input: { prompt: text, output_format: "url", language_boost: (MED_LANG[lang] || MED_LANG.en).boost,
      voice_setting: { voice_id: v.voice, speed: 1, vol: 1, pitch: 0 } } };
  }
  return { model: "eleven", input: { text, voice: v.voice, language_code: lang, stability: 0.5 } };
}
