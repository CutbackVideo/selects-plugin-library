// The source's language. `short` lowers the thresholds for a topic of a few words.
export function medDetectLang(text, short = false) {
  const t = slice(text, 0, 5000);
  const count = (re) => (t.match(re) || []).length;
  const k = short ? 1 : 20;
  if (count(/[\uac00-\ud7a3]/gu) > k) return "ko";
  if (count(/[\u3040-\u30ff]/gu) > k) return "ja";
  if (count(/[\u4e00-\u9fff]/gu) > (short ? 1 : 40)) return "zh";
  const ws = t.toLowerCase().match(/[a-z\u00e0-\u00ff\u011f\u00fc\u015f\u0131\u00f6\u00e7]+/gu) || [];
  let best = "en", top = -1;
  for (const [code, list] of Object.entries(MED_STOPWORDS)) {
    const set = new Set(list.split(" "));
    const n = ws.filter((w) => set.has(w)).length;
    if (n > top) { best = code; top = n; }
  }
  return top > (short ? 0 : 3) ? best : "en";
}
