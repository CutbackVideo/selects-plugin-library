export const MED_GEN_DEADLINE_MS = 45 * 60 * 1000;
export const MED_GEN_POLL_MS = 4000;
export const MED_DELIVERY_RETRIES = 3;
// Submits each request that has no acknowledged job under its key (an unacknowledged submission is submitted again
// under the SAME key, which the host resolves to the same job), records the job id before and after, and observes
// until every job is delivered, failed, or unresolved. `gen` is the job's request map (mutated); `api` is
// { submit(q) -> jobId, list(jobIds) -> snapshots, retryDelivery(jobId) }; `opts` carries persist, sleep, now,
// stopped and progress. Returns { failed: [{gen, code}], unresolved: [{gen, reason}] }. Nothing here ever submits
// under a new key: that is the caller's decision, for known failures only.
// Multi-candidate stages (keyframe candidates, scene clip takes, transition takes): a scene needs one delivered
// candidate. Once every scene that can still deliver has one, and only non-terminal jobs are left (for example the
// host's submission_unknown, which the host recovers by itself and which is never resubmitted), the stage waits
// MED_GEN_GRACE_MS after its last delivery and then goes on without them. They are not cancelled or resubmitted: the
// record is marked ignored ("unresolved"), listed in the run summary, and a late result is not used.
export const MED_GEN_GRACE_MS = 3 * 60 * 1000;
// What a candidate request shares with its siblings: its key without the candidate letter and the attempt, i.e. job,
// stage, scene and every choice in the key (model tag, reference, chosen keyframe or clips, revision). A regenerated
// keyframe (R<k>) keeps its letter, so only the same regeneration matches. null for a key that had to be hashed.
export function medKeySignature(key) {
  const m = /^(.+-(?:kf|clip|tr)-\d+)-([A-C]|R\d+)-\d+(.*)$/.exec(String(key || ""));
  if (!m) return null;
  return `${m[1]}|${/^R/.test(m[2]) ? m[2] : "C"}|${m[3]}`;
}
const groupOf = (g) => g.split(":").slice(0, 2).join(":");
export async function medRunGenerations(reqs, gen, api, opts) {
  const o = { deadlineMs: MED_GEN_DEADLINE_MS, pollMs: MED_GEN_POLL_MS, deliveryRetries: MED_DELIVERY_RETRIES, graceMs: MED_GEN_GRACE_MS,
    multi: false, stopped: () => false, progress: () => {}, ...opts };
  const failed = [], unresolved = [], ignored = [], pending = [];
  const delivered = new Set();
  let done = 0, lastDelivery = null;
  const ignore = (q, reason) => { gen[q.gen] = { ...gen[q.gen], ignored: reason }; ignored.push({ gen: q.gen, reason }); };
  for (const q of reqs) {
    const cur = gen[q.gen];
    const same = cur && cur.key === q.key;
    if (same && cur.path) { done++; delivered.add(groupOf(q.gen)); continue; }
    if (same && cur.failed) { failed.push({ gen: q.gen, code: cur.failed, ...(cur.policy ? { policy: true } : {}) }); continue; }
    if (same && cur.ignored && o.multi) { ignored.push({ gen: q.gen, reason: cur.ignored }); continue; }
    if (!same || !cur.jobId) {
      if (o.stopped()) throw new Error("stopped");
      gen[q.gen] = { key: q.key, attempt: q.attempt, phase: "submitting" };
      await o.persist();
      let jobId;
      try { jobId = await api.submit(q); } catch (e) {
        // A submission the host refused, naming the content policy, never became a job: a known rejection. Any other
        // error leaves the recorded submission unresolved (the same key is used again on resume).
        if (!new RegExp(`\\b${MED_POLICY_CODE}\\b`).test(String(e && e.message || e))) throw e;
        gen[q.gen] = { key: q.key, attempt: q.attempt, failed: MED_POLICY_CODE, policy: true };
        await o.persist();
        failed.push({ gen: q.gen, code: MED_POLICY_CODE, policy: true });
        continue;
      }
      if (!jobId) throw new Error("Generation submission is unknown. Resume to reconnect with the same request key.");
      gen[q.gen] = { key: q.key, attempt: q.attempt, jobId };
      await o.persist();
    }
    pending.push(q);
  }
  // A scene already served by a delivered sibling candidate in this job's records counts as served, whichever pass or
  // call delivered it (a retry pass asks only for the failed candidate) — but only a sibling of the same request: the
  // same scene, keyframe model, reference, chosen keyframe or clips and sentence revision (medKeySignature); outputs
  // of an older model or revision never count.
  for (const q of reqs) {
    const g = groupOf(q.gen), sig = medKeySignature(q.key);
    if (delivered.has(g) || !sig) continue;
    if (Object.entries(gen).some(([k, v]) => k !== q.gen && groupOf(k) === g && v && v.path && medKeySignature(v.key) === sig)) delivered.add(g);
  }
  if (delivered.size) lastDelivery = o.now();
  const retries = new Map(), status = new Map();
  const deadline = o.now() + o.deadlineMs;
  const statusOf = (q) => status.get(q.gen) || "running";
  // Every scene that can still deliver (not all of its candidates failed) has a delivered candidate.
  const allServed = (left) => [...new Set([...left.map((q) => groupOf(q.gen))])].every((g) => delivered.has(g));
  let left = pending;
  while (left.length) {
    if (o.stopped()) throw new Error("stopped");
    if (o.now() > deadline) {
      for (const q of left) {
        if (o.multi && delivered.has(groupOf(q.gen))) ignore(q, "unresolved");
        else unresolved.push({ gen: q.gen, reason: "still " + statusOf(q) });
      }
      break;
    }
    const rows = await api.list(left.map((q) => gen[q.gen].jobId));
    if (!Array.isArray(rows)) throw new Error("Generation progress could not be read.");
    const byId = new Map(rows.map((j) => [j.jobId, j]));
    const next = [];
    for (const q of left) {
      const entry = gen[q.gen];
      const row = byId.get(entry.jobId);
      if (row) status.set(q.gen, [row.status, row.deliveryStatus].filter(Boolean).filter((x, i, a) => a.indexOf(x) === i).join(" / "));
      const c = medClassifyJob(row);
      if (c.state === "delivered") { gen[q.gen] = { ...entry, path: c.path }; done++; delivered.add(groupOf(q.gen)); lastDelivery = o.now(); }
      else if (c.state === "failed") {
        gen[q.gen] = { ...entry, failed: c.code, ...(c.policy ? { policy: true } : {}) };
        failed.push({ gen: q.gen, code: c.code, ...(c.policy ? { policy: true } : {}) });
      }
      else if (c.state === "delivery_failed") {
        const n = retries.get(entry.jobId) || 0;
        if (n < o.deliveryRetries) { retries.set(entry.jobId, n + 1); await api.retryDelivery(entry.jobId); next.push(q); }
        else if (o.multi && delivered.has(groupOf(q.gen))) ignore(q, "delivery " + c.code);
        else unresolved.push({ gen: q.gen, reason: "delivery " + c.code });
      } else next.push(q);
    }
    // The grace period: every scene served, only non-terminal jobs left, 3 minutes since the last delivery.
    if (o.multi && next.length && allServed(next) && lastDelivery !== null && o.now() - lastDelivery >= o.graceMs) {
      for (const q of next) ignore(q, "unresolved");
      next.length = 0;
    }
    await o.persist();
    o.progress(done, reqs.length);
    left = next;
    if (left.length) await o.sleep(o.pollMs);
  }
  return { failed, unresolved, ignored };
}

// One kind of request for `only` ids, each at the attempt its record is on (a recorded request is never re-keyed).
// A request the host reports as failed gets one new attempt (a new request key, a new paid job) unless it was refused
// for content policy (the same input would be refused again); an unresolved one stops the run for the user to decide.
// `ctx`: { gen, requests(kind, ids, attempt) -> requests, generate(requests) -> {failed, unresolved}, unresolved(list)
// -> Error }. Returns what is still failed: [{gen, code, policy?}].
const genId = (g) => g.split(":").slice(1).join("");
export async function medGenerateKind(ctx, kind, only) {
  if (!only.length) return [];
  const atAttempts = async (pairs) => {
    const groups = new Map();
    for (const [id, a] of pairs) groups.set(a, [...(groups.get(a) || []), id]);
    const out = [];
    for (const [a, ids] of groups) out.push(...(await ctx.requests(kind, ids, a)).filter((q) => ids.includes(genId(q.gen))));
    return out;
  };
  const base = await ctx.requests(kind, only, 1);
  const multi = ["keyframes", "kfregen", "clips", "transitions"].includes(kind);
  const first = await ctx.generate(await atAttempts(base.map((q) => [genId(q.gen), (ctx.gen[q.gen] && ctx.gen[q.gen].attempt) || 1])), { multi });
  if (first.unresolved.length) throw ctx.unresolved(first.unresolved);
  const retry = first.failed.filter((f) => !f.policy);
  if (!retry.length) return first.failed;
  const second = await ctx.generate(await atAttempts(retry.map((f) => [genId(f.gen), ((ctx.gen[f.gen] && ctx.gen[f.gen].attempt) || 1) + 1])), { multi });
  if (second.unresolved.length) throw ctx.unresolved(second.unresolved);
  return [...first.failed.filter((f) => f.policy), ...second.failed];
}
const takeLetters = () => Array.from(MED_LETTERS.slice(0, MED_TAKES));
// Scenes whose clip no take delivered because Kling refused it for content policy, and for which the user has not
// chosen the still image: the run stops and shows them, one by one, with the user's two choices.
export function medPolicyScenes(sceneIds, gen, picks) {
  return sceneIds.filter((n) => {
    const takes = takeLetters().map((c) => gen[`clip:${n}:${c}`]).filter(Boolean);
    return !takes.some((t) => t.path) && takes.some((t) => t.policy) && !asObj(picks.still)[n];
  });
}
// The scene-clip stage. First, any keyframe the user explicitly asked to regenerate (picks.regen, set only by the
// panel's "Regenerate this scene's keyframe" button) is made and chosen; then every scene's clips are generated (a
// changed keyframe changes the clip request key). Nothing here replaces a keyframe or resubmits on its own.
// `ctx` adds readPicks() and writePicks(picks). Returns { blocked: scenes refused for content policy and waiting for
// the user, regenFailed: asked-for keyframes that did not arrive, still: scenes without a clip }.
export async function medClipsStage(ctx, sceneIds) {
  const picks0 = await ctx.readPicks();
  const regen = asObj(picks0.regen);
  const asked = sceneIds.filter((n) => regen[n] && regen[n].k >= 1 && picks0.kf[n] !== medRegenLetter(regen[n].k));
  const regenFailed = [];
  if (asked.length) {
    await medGenerateKind(ctx, "kfregen", asked);
    const picks = await ctx.readPicks();
    for (const n of asked) {
      const c = medRegenLetter(regen[n].k);
      if ((ctx.gen[`kf:${n}:${c}`] || {}).path) picks.kf[n] = c;
      else regenFailed.push(n);
    }
    await ctx.writePicks(picks);
  }
  await medGenerateKind(ctx, "clips", sceneIds);
  const blocked = medPolicyScenes(sceneIds, ctx.gen, await ctx.readPicks());
  const still = sceneIds.filter((n) => !blocked.includes(n) && !takeLetters().some((c) => (ctx.gen[`clip:${n}:${c}`] || {}).path));
  return { blocked, regenFailed, still };
}

