// Builds panel.tsx from src/:
//   1. src/templates/generated.ts  each src/templates/<type>.tsx as a tsxCode string, paired with its Inspector
//                                  controls (PARAM_SCHEMAS), timeIndependent flag and clip label from schemas.ts;
//                                  a `// @heritage` line becomes the shared helpers in src/heritage/shared.jsx
//   2. panel.tsx                   one esbuild bundle of src/Panel.tsx that imports only react, with the shared
//                                  app-update guard appended
// The bundle is ASCII: Hangul in src/ (written as \uXXXX) stays escaped, as the public-source check requires.
// usage: node build.mjs [path/to/esbuild]   (ESBUILD also names it; PANEL_OUT overrides the output)
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const spec = process.argv[2] || process.env.ESBUILD || "esbuild";
const esbuild = require(spec.startsWith(".") || spec.startsWith("/") ? resolve(spec) : spec);
const manifest = JSON.parse(readFileSync(join(ROOT, "plugin.json"), "utf8"));
const panelOut = process.env.PANEL_OUT ? resolve(process.env.PANEL_OUT) : join(ROOT, "panel.tsx");
const ALLOWED_IMPORTS = new Set(["react", "react/jsx-runtime"]);

function writeIfChanged(path, text) {
  let old = null;
  try { old = readFileSync(path, "utf8"); } catch {}
  if (old !== text) writeFileSync(path, text);
}

// 1. templates
{
  const dir = join(ROOT, "src", "templates");
  const types = readdirSync(dir).filter((f) => f.endsWith(".tsx")).map((f) => f.slice(0, -4)).sort();
  const lines = [
    "// Generated by build.mjs from src/templates/*.tsx; do not edit.",
    'import { PARAM_SCHEMAS, TIME_INDEPENDENT, LABELS } from "./schemas.ts";',
    "export const TEMPLATES = {",
  ];
  const heritage = readFileSync(join(ROOT, "src", "heritage", "shared.jsx"), "utf8").trimEnd();
  for (const t of types) {
    const code = readFileSync(join(dir, t + ".tsx"), "utf8").replace(/^\/\/ @heritage$/m, () => heritage);
    lines.push(`  ${JSON.stringify(t)}: { tsxCode: ${JSON.stringify(code)}, editableParameters: (PARAM_SCHEMAS as any)[${JSON.stringify(t)}] ?? [], timeIndependent: !!(TIME_INDEPENDENT as any)[${JSON.stringify(t)}], label: (LABELS as any)[${JSON.stringify(t)}] ?? ${JSON.stringify(t)} },`);
  }
  lines.push("} as const;", "");
  writeIfChanged(join(dir, "generated.ts"), lines.join("\n"));

  // 1b. src/templates/entrance.generated.ts  ENTRANCE[type](data, fps, durationInFrames): the `natural` each scene
  //     template passes to useScene, i.e. when its last animation (count-ups and brushes included) ends at normal
  //     speed. The template sources run with stub hooks and a useScene that records the value, so the timing stays
  //     written once, in the template. SCENE[type](data, fps, durationInFrames, frame, h) runs the same source at one
  //     frame with `h` as the element factory, so tests can compare the tree at the seek frame with the last frame.
  const scenes = types.filter((t) => /\buseScene\(/.test(readFileSync(join(dir, t + ".tsx"), "utf8")));
  const body = [
    heritage.replace(/^function useScene\(/m, "function realUseScene("),
    "let NATURAL = null, CONFIG = { frame: 0, video: null };",
    "const useVideoConfig = () => CONFIG.video, useCurrentFrame = () => CONFIG.frame;",
    "function useScene(data, natural = 0) { if (NATURAL === null) NATURAL = natural; return realUseScene(data, natural); }",
    "const SCENE = {",
  ];
  for (const t of scenes) {
    const code = readFileSync(join(dir, t + ".tsx"), "utf8")
      .replace(/^import .*;$/gm, "")
      .replace(/^\/\/ @heritage$/m, "")
      .replace(/^export default function (\w+)/m, "function Scene");
    body.push(`  ${JSON.stringify(t)}: (data) => {
${code}
    return Scene({ data });
  },`);
  }
  body.push(
    "};",
    "function run(type, data, fps, durationInFrames, frame, h) {",
    "  const before = [H, NATURAL, CONFIG];",
    "  H = h; NATURAL = null; CONFIG = { frame, video: { fps, durationInFrames, width: 1080, height: 1920 } };",
    "  try { const tree = SCENE[type](data); return { tree, natural: NATURAL }; }",
    "  finally { [H, NATURAL, CONFIG] = before; }",
    "}",
    "const ENTRANCE = {};",
    "for (const t of Object.keys(SCENE)) ENTRANCE[t] = (data, fps, durationInFrames) => {",
    "  const r = run(t, data, fps, durationInFrames, 0, NULL_H);",
    "  if (typeof r.natural !== 'number') throw new Error(t + ' did not reach useScene');",
    "  return r.natural;",
    "};",
    "const renderScene = (type, data, fps, durationInFrames, frame, h) => run(type, data, fps, durationInFrames, frame, h).tree;",
    "export { ENTRANCE, HOLD, renderScene };",
  );
  const js = esbuild.transformSync(body.join("\n"), { loader: "jsx", jsx: "transform", jsxFactory: "STUB", jsxFragment: "STUB", charset: "ascii", legalComments: "none", format: "esm" }).code;
  writeIfChanged(join(dir, "entrance.generated.ts"), [
    "// Generated by build.mjs from src/templates/*.tsx and src/heritage/shared.jsx; do not edit.",
    "// @ts-nocheck",
    "const FRAGMENT = 'Fragment', NULL_H = () => null;",
    "let H = NULL_H;",
    "const React = { useState: (v) => [typeof v === 'function' ? v() : v], useEffect: () => {}, useMemo: (f) => f(), useRef: () => ({}), Fragment: FRAGMENT };",
    "const STUB = (type, props, ...children) => H(type === STUB ? FRAGMENT : type, props, children), Img = 'img', delayRender = () => 0, continueRender = () => {}, cancelRender = () => {};",
    js.trimEnd(),
    "",
  ].join("\n"));
}

// 2. the panel
const header = [
  "// @name " + manifest.name,
  "// @icon newspaper",
  "// Turns a news article into a one-minute vertical news short: script checked against the article, editor",
  "// review, narration, a scene per sentence from article photos and data cards, captions, in an editable Draft.",
].join("\n");
const result = esbuild.buildSync({
  absWorkingDir: ROOT,
  entryPoints: [join(ROOT, "src", "Panel.tsx")],
  outfile: panelOut,
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  external: [...ALLOWED_IMPORTS],
  jsx: "automatic",
  charset: "ascii",
  legalComments: "none",
  minify: false,
  metafile: true,
  logLevel: "warning",
  define: { __NEWS_MINUTE_VERSION__: JSON.stringify(manifest.version) },
  banner: { js: header },
  footer: { js: "// app-update-guard:start\n" + readFileSync(join(ROOT, "../../shared/app-update-guard.ts"), "utf8").trimEnd() + "\n// app-update-guard:end" },
});
const imports = new Set();
for (const o of Object.values(result.metafile.outputs)) for (const i of o.imports || []) if (i.external) imports.add(i.path);
const bad = [...imports].filter((i) => !ALLOWED_IMPORTS.has(i));
if (bad.length) {
  console.error("The panel may import only react; it imports " + bad.join(", "));
  process.exit(1);
}
const text = readFileSync(panelOut, "utf8");
if (/[^\x00-\x7f]/.test(text)) {
  console.error("panel.tsx must be ASCII");
  process.exit(1);
}
console.log("built", relative(process.cwd(), panelOut) || panelOut, statSync(panelOut).size, "bytes (" + manifest.name + " " + manifest.version + ")");
