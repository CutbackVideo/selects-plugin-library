LICENSE_OK = re.compile(r"public domain|^pd\b|cc0|cc[- ]by(-sa)?[- ]?\d", re.I)
LICENSE_BAD = re.compile(r"\bnc\b|\bnd\b|non-?commercial|no ?deriv", re.I)


def wiki_portrait(title, dest):
    d = get_json("https://en.wikipedia.org/w/api.php?" + urllib.parse.urlencode(
        {"action": "query", "prop": "pageimages", "piprop": "original|name", "titles": title, "format": "json",
         "redirects": 1}))
    pages = list(((d or {}).get("query") or {}).get("pages", {}).values())
    name = pages[0].get("pageimage") if pages else None
    if not name:
        return {"ok": False, "error": "no lead image"}
    m = get_json("https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode(
        {"action": "query", "titles": "File:" + name, "prop": "imageinfo", "iiprop": "extmetadata", "format": "json"}))
    cp = list(((m or {}).get("query") or {}).get("pages", {}).values())
    em = ((cp[0].get("imageinfo") or [{}])[0].get("extmetadata") or {}) if cp else {}
    lic = (em.get("LicenseShortName") or {}).get("value", "")
    if not LICENSE_OK.search(lic) or LICENSE_BAD.search(lic):
        return {"ok": False, "file": name, "license": lic}
    artist = re.sub(r"^(Photographer|Photo|Author)\s*:\s*", "", strip_tags((em.get("Artist") or {}).get("value", "")), flags=re.I)[:60]
    code, b = http_get("https://commons.wikimedia.org/w/index.php?title=Special:Redirect/file/" +
                       urllib.parse.quote(name) + "&width=900", UA_API, timeout=60)
    if code >= 300 or not b:
        return {"ok": False, "file": name, "error": "download %s" % code}
    with open(dest, "wb") as f:
        f.write(b)
    return {"ok": True, "file": name, "license": lic, "artist": artist}


def cmd_portraits(job):
    plan = job.plan()
    portraits = job.data.setdefault("portraits", {})
    for c in plan["cast"]:
        if c["key"] not in portraits:
            try:
                r = wiki_portrait(c["wiki"], job.p("portraits", "%s.jpg" % c["key"]))
            except EngineError as e:
                r = {"ok": False, "error": str(e)}
            portraits[c["key"]] = dict(r, name=c["name"])
    # A person without a free photo becomes a faceless paper silhouette with a name card; the image
    # model must never draw a real person's likeness from memory.
    missing = {k for k, v in portraits.items() if not v.get("ok")}
    for _, s in shots_of(plan):
        for k in [k for k in s["cast"] if k in missing]:
            name = next(c["name"] for c in plan["cast"] if c["key"] == k)
            s["scene"] = s["scene"].replace(name, "a faceless paper silhouette with a name card '%s'" % name.split()[-1].upper())
            s["cast"].remove(k)
    save(job.p("plan.json"), plan)
    job.data["stage"] = "portraits"
    job.save()
    out({"ok": True, "found": sorted(k for k in portraits if k not in missing),
         "missing": [portraits[k]["name"] for k in sorted(missing)]})


