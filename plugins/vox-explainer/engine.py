def keyframe_prompt(plan, beat, shot):
    world = ("%s Palette: %s. %s Print finish: %s. SCENE (as layered paper cut-outs): %s. No big headline in "
             "this shot (a small accent only); it is a cut-in detail. Aspect ratio 9:16."
             % (THEME["idiom"], THEME["palette"], MECHANICS.format(bg=beat["bg"]), THEME["finish"], shot["scene"]))
    if shot["cast"]:
        cast = {c["key"]: c for c in plan["cast"]}
        who = "; ".join("image %d is %s" % (i + 1, cast[k]["name"]) for i, k in enumerate(shot["cast"]))
        clothes = "; ".join("%s wears %s" % (cast[k]["name"], cast[k]["wardrobe"]) for k in shot["cast"])
        return FACE_LOCK.format(who=who, clothes=clothes) + world + FACE_GUARD + TEXT_GUARD + LAYOUT_GUARD
    return world + NO_PEOPLE + TEXT_GUARD + LAYOUT_GUARD


def motion_prompt(beat, shot):
    amp = "calm" if shot["has_text"] else "punchy"   # LESSON: busy motion garbled text and bent props
    text_lock = ("Keep every printed word sharp, legible and stable — do not warp or wobble the lettering. "
                 if shot["has_text"] else "")
    guard = ((FREEZE if shot["cast"] else "") + text_lock +
             "Keep the layout stable. Stay flat 2D — no 3D rotation, no perspective change, camera parallel "
             "to the poster. ONE continuous move that does not loop, retract or reset. Rigid paper — no "
             "morph/melt; straight posts and poles stay straight and upright. Animate the motion only; don't "
             "re-render the picture.")
    return ("Animate this still into a mixed-media paper-collage MOTION GRAPHIC, printed cut-outs, not "
            "photoreal.\nCAMERA (one move only): %s.\nELEMENT MOTION (%s): %s. Elements move as paper cut-outs "
            "(slide, flap, hinge, pop).\nAESTHETIC: keep the torn-paper, tape, halftone, newsprint and "
            "paper-stencil textures and the bold flat background.\nCOLOR: %s, high contrast.\nCONSTRAINTS: %s"
            % (CAMERA[shot["camera"]], AMPLITUDE[amp], shot["motion"], beat["bg"], guard))[:2500]


def kling_seconds(need):
    """Shortest Kling length that covers the shot (it returns duration + 0.04 s; min 3, max 15)."""
    return int(min(15, max(3, math.ceil(need + 0.05))))


def cmd_requests(job, kind, only, attempt):
    plan = job.plan()
    reqs = []

    def spec(k, sid, tool, model, inp, uploads=None, folder=kind):
        name = "%s_%s_%s_%d" % (job.id, k, sid, attempt) if sid else "%s_%s_%d" % (job.id, k, attempt)
        return {"key": ("%s-%s-%s-%d" % (job.id, k, sid, attempt)) if sid else "%s-%s-%d" % (job.id, k, attempt),
                "gen": "%s:%s" % (k, sid) if sid else k, "id": sid, "attempt": attempt, "tool": tool,
                "modelId": MODEL[model], "input": inp, "uploads": uploads or {}, "outputName": name,
                "folder": os.path.join(job.dir, "gen", folder)}

    if kind == "narration":
        lang = plan["lang"]
        for b in plan["beats"]:
            if not only or str(b["n"]) in only:
                reqs.append(spec("narr", str(b["n"]), "audio", "tts",
                                 {"text": b["narration"], "voice": VOICE, "language_code": lang, "stability": 0.5}))
    elif kind == "keyframes":
        for b, s in shots_of(plan):
            if only and s["id"] not in only:
                continue
            inp = {"prompt": keyframe_prompt(plan, b, s), "aspect_ratio": "9:16", "resolution": "2K",
                   "num_images": 1, "output_format": "png"}
            uploads = {}
            if s["cast"]:
                slots = ["p%d" % (i + 1) for i in range(len(s["cast"]))]
                inp["image_urls"] = ["selects-input:" + x for x in slots]
                uploads = {slot: os.path.join(job.dir, "portraits", "%s.jpg" % k) for slot, k in zip(slots, s["cast"])}
            reqs.append(spec("kf", s["id"], "image", "edit" if s["cast"] else "t2i", inp, uploads))
    elif kind == "clips":
        tl = load(os.path.join(job.dir, "timeline.json"))
        need = {x["shot"]: x for x in tl["segments"]}
        for b, s in shots_of(plan):
            if only and s["id"] not in only:
                continue
            kf = job.file("kf:" + s["id"])
            if not kf:
                raise EngineError("keyframe missing: " + s["id"])
            reqs.append(spec("clip", s["id"], "video", "i2v",
                             {"prompt": motion_prompt(b, s), "start_image_url": "selects-input:start",
                              "duration": str(need[s["id"]]["kling"]), "generate_audio": False},
                             {"start": kf}))
    elif kind == "music":
        tl = load(os.path.join(job.dir, "timeline.json"))
        reqs.append(spec("music", "", "audio", "music",
                         {"prompt": MUSIC_PROMPT, "force_instrumental": True, "music_length_ms": tl["music_ms"]}))
    else:
        raise EngineError("unknown request kind " + kind)
    out({"ok": True, "requests": reqs})


# ---- timeline: narration timing from the audio itself --------------------------------------------
def silences(path):
    r = subprocess.run([find_tool("ffmpeg"), "-hide_banner", "-nostats", "-i", path, "-af",
                        "silencedetect=noise=-38dB:d=0.12", "-f", "null", "-"], capture_output=True, text=True)
    starts = [float(x) for x in re.findall(r"silence_start: ([\d.]+)", r.stderr)]
    ends = [float(x) for x in re.findall(r"silence_end: ([\d.]+)", r.stderr)]
    return list(zip(starts, ends + [None] * (len(starts) - len(ends))))


def align_words(text, dur, sil, lang):
    """Word start times without provider timestamps. Speech between the leading and trailing silence is
    shared out by each word's speech weight, and every internal pause is placed at the word boundary
    nearest its position, preferring boundaries after punctuation. Returns [(word, start, end)]."""
    words = text.split()
    wts = [word_weight(w, lang) for w in words]
    sil = [(a, b if b is not None else dur) for a, b in sil]
    s0 = sil[0][1] if sil and sil[0][0] <= 0.05 else 0.0
    s1 = sil[-1][0] if sil and sil[-1][1] >= dur - 0.05 and sil[-1][0] > s0 else dur
    inner = [(a, b) for a, b in sil if a > s0 + 0.05 and b < s1 - 0.05]
    speech = max(0.1, (s1 - s0) - sum(b - a for a, b in inner))
    total = sum(wts)
    cum, acc = [], 0.0
    for w in wts:
        acc += w
        cum.append(acc)          # cumulative weight after word i
    pause_after = [0.0] * len(words)
    used, removed = set(), 0.0
    avg = total / max(1, len(words))
    for a, b in inner:
        pos = (a - s0 - removed) / speech * total
        best, score = None, None
        for j in range(len(words) - 1):
            if j in used:
                continue
            sc = abs(cum[j] - pos) - (0.8 * avg if re.search(r"[.,!?;:。、，！？]$", words[j]) else 0)
            if score is None or sc < score:
                best, score = j, sc
        if best is not None:
            used.add(best)
            pause_after[best] += b - a
        removed += b - a
    out_words, extra = [], 0.0
    for i, w in enumerate(words):
        start = s0 + (cum[i] - wts[i]) / total * speech + extra
        end = s0 + cum[i] / total * speech + extra
        out_words.append((w, round(start, 3), round(end, 3)))
        extra += pause_after[i]
    return out_words


def cmd_timeline(job):
    plan = job.plan()
    lang = plan["lang"]
    t, segs, narr, heads, cues = 0.0, [], [], [], []
    for b in plan["beats"]:
        path = job.file("narr:%d" % b["n"])
        if not path:
            raise EngineError("narration missing: beat %d" % b["n"])
        nd = media_duration(path)
        ws = align_words(b["narration"], nd, silences(path), lang)
        last = b["n"] == len(plan["beats"])
        length = LEAD + nd + TAIL + (END_HOLD if last else 0)
        cuts = [0.0]
        if len(b["shots"]) == 2 and b.get("cut_index") and b["cut_index"] < len(ws):
            cuts.append(round(LEAD + ws[b["cut_index"]][1] - 0.05, 3))
        cuts.append(round(length, 3))
        if len(cuts) == 3 and (cuts[1] < 1.5 or length - cuts[1] < 1.5):
            cuts = [0.0, cuts[2]]
            b["shots"] = b["shots"][:1]
        for i, s in enumerate(b["shots"]):
            need = cuts[i + 1] - cuts[i]
            segs.append({"shot": s["id"], "start": round(t + cuts[i], 3), "need": round(need, 3), "kling": kling_seconds(need)})
        narr.append({"beat": b["n"], "file": path, "start": round(t + LEAD, 3), "dur": round(nd, 3)})
        heads.append({"beat": b["n"], "text": b["title"], "start": round(t, 3), "end": round(t + length, 3)})
        lines = b["captions"]
        if sum(len(l.split()) for l in lines) != len(ws):
            lines = auto_captions(" ".join(w[0] for w in ws), LANG[lang]["cap"])
        idx, starts = 0, []
        for line in lines:
            starts.append(ws[min(idx, len(ws) - 1)][1])
            idx += len(line.split())
        for i, line in enumerate(lines):
            a = t + LEAD + starts[i]
            e = t + LEAD + (starts[i + 1] if i + 1 < len(lines) else nd + 0.15)
            cues.append({"text": line.rstrip(",.、，"), "start": round(a, 3), "end": round(e, 3)})
        t += length
    save(job.p("plan.json"), plan)
    # LESSON: music bills by started minute; 60.03 s cost two. Stay under the boundary.
    need_s = t + 2
    music_s = min(math.ceil(need_s), 60 * math.ceil(need_s / 60.0) - 1)
    save(job.p("timeline.json"), {"total": round(t, 3), "segments": segs, "narration": narr, "headlines": heads,
                                  "captions": cues, "music_ms": int(music_s * 1000)})
    job.data["stage"] = "timed"
    job.save()
    out({"ok": True, "seconds": round(t, 3), "shots": len(segs), "videoSeconds": sum(s["kling"] for s in segs)})


