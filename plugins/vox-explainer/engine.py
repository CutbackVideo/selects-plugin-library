def main(argv):
    if len(argv) < 2:
        raise EngineError("usage: engine.py <command> [job]")
    cmd = argv[1]
    if cmd == "check":
        return cmd_check()
    job = Job(argv[2])
    rest = argv[3:]
    attempt = int(rest[rest.index("--attempt") + 1]) if "--attempt" in rest else 1
    pos = [x for i, x in enumerate(rest) if not x.startswith("--") and (i == 0 or rest[i - 1] != "--attempt")]
    if cmd == "requests":
        only = set(pos[1].split(",")) if len(pos) > 1 and pos[1] else None
        return cmd_requests(job, pos[0], only, attempt)
    only = set(pos[0].split(",")) if pos and pos[0] else None
    handlers = {"fetch": lambda: cmd_fetch(job), "validate": lambda: cmd_validate(job),
                "portraits": lambda: cmd_portraits(job), "timeline": lambda: cmd_timeline(job),
                "sheet": lambda: cmd_sheet(job, only), "kenburns": lambda: cmd_kenburns(job, sorted(only or [])),
                "assembly": lambda: cmd_assembly(job)}
    if cmd not in handlers:
        raise EngineError("unknown command " + cmd)
    return handlers[cmd]()


