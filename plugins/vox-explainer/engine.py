def cmd_sheet(job, only=None):
    plan = job.plan()
    ff = find_tool("ffmpeg")
    ids = [s["id"] for _, s in shots_of(plan) if not only or s["id"] in only]
    font = "/System/Library/Fonts/Supplemental/Arial.ttf"
    sheets = []
    for part in range(0, len(ids), 12):
        chunk = ids[part:part + 12]
        cols = 4 if len(chunk) > 6 else max(1, min(3, len(chunk)))
        args, filt = [], ""
        for i, sid in enumerate(chunk):
            args += ["-i", job.file("kf:" + sid)]
            label = ("drawtext=fontfile=%s:text='%s':x=8:y=8:fontsize=34:fontcolor=white:box=1:boxcolor=black@0.8:boxborderw=6,"
                     % (font, sid)) if os.path.exists(font) else ""
            filt += "[%d:v]scale=270:480,%spad=276:486:3:3:white[v%d];" % (i, label, i)
        layout = "|".join("%d_%d" % ((i % cols) * 276, (i // cols) * 486) for i in range(len(chunk)))
        stack = "".join("[v%d]" % i for i in range(len(chunk))) + (
            "xstack=inputs=%d:layout=%s:fill=white" % (len(chunk), layout) if len(chunk) > 1 else "null")
        dest = job.p("check", "sheet_%d_%d.jpg" % (int(time.time()), part // 12 + 1))
        r = subprocess.run([ff, "-loglevel", "error", "-y"] + args + ["-filter_complex", filt + stack, "-frames:v", "1",
                                                                       "-q:v", "4", dest], capture_output=True, text=True)
        if r.returncode != 0:
            raise EngineError("sheet: " + r.stderr[-300:])
        sheets.append({"path": dest, "shots": chunk})
    cast = {c["key"]: c["name"] for c in plan["cast"]}
    expect = [{"shot": s["id"], "people": [cast[k] for k in s["cast"]],
               "words": re.findall(r"['\"“‘]([^'\"”’]{1,40})['\"”’]", s["scene"]), "scene": s["scene"][:300]}
              for _, s in shots_of(plan) if not only or s["id"] in only]
    out({"ok": True, "sheets": sheets, "expect": expect})


def ken_burns(img, dest, dur, zoom_in=True):
    frames = int(math.ceil(dur * FPS))
    z = "min(zoom+0.0009,1.18)" if zoom_in else "if(eq(on,1),1.18,max(zoom-0.0009,1.0))"
    vf = ("[0:v]scale=%d:%d:force_original_aspect_ratio=increase,crop=%d:%d,boxblur=26:2[bg];"
          "[0:v]scale=%d:%d:force_original_aspect_ratio=decrease[fg];"
          "[bg][fg]overlay=(W-w)/2:(H-h)/2,setsar=1,scale=%d:%d,"
          "zoompan=z='%s':d=%d:x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':s=%dx%d:fps=%d[v]"
          % (W, H, W, H, W, H, W * 2, H * 2, z, frames, W, H, FPS))
    r = subprocess.run([find_tool("ffmpeg"), "-y", "-loglevel", "error", "-loop", "1", "-i", img, "-filter_complex", vf,
                        "-map", "[v]", "-t", "%.3f" % dur, "-c:v", "libx264", "-pix_fmt", "yuv420p", dest],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise EngineError("ken burns: " + r.stderr[-300:])


