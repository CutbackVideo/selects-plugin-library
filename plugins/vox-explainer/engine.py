def meta(s, prop):
    m = re.search(r'<meta[^>]+(?:property|name)=["\']%s["\'][^>]+content=["\']([^"\']*)' % re.escape(prop), s)
    if not m:
        m = re.search(r'<meta[^>]+content=["\']([^"\']*)["\'][^>]+(?:property|name)=["\']%s["\']' % re.escape(prop), s)
    return html.unescape(m.group(1)).strip() if m else ""


def korean_name(n):
    """Arc stores Korean bylines as 'given family' ('\uad6d\ud76c \ubc15'); print them the Korean way ('\ubc15\uad6d\ud76c')."""
    m = re.match(r"^([\uac00-\ud7a3]{1,3}) ([\uac00-\ud7a3]{1,2})$", (n or "").strip())
    return m.group(2) + m.group(1) if m else n


def extract_article(url, s):
    title = meta(s, "og:title") or strip_tags((re.search(r"<title>(.*?)</title>", s, re.S) or [None, ""])[1])
    art = {"url": url, "title": title, "subtitle": "", "description": meta(s, "og:description"),
           "source": meta(s, "og:site_name"), "date": meta(s, "article:published_time"),
           "byline": meta(s, "author") or meta(s, "dable:author"), "body": "", "method": ""}
    m = re.search(r"Fusion\.globalContent\s*=\s*(\{.*?\});\s*Fusion\.", s, re.S)   # Arc XP (Chosun and others)
    if m:
        try:
            d = json.loads(m.group(1))
            paras = [strip_tags(e.get("content", "")) for e in d.get("content_elements", []) if e.get("type") == "text"]
            if paras:
                art["body"] = "\n".join(p for p in paras if p)
                art["title"] = (d.get("headlines") or {}).get("basic") or art["title"]
                art["subtitle"] = strip_tags(re.sub(r"<br\s*/?>", " / ", (d.get("subheadlines") or {}).get("basic") or ""))
                by = [korean_name(c.get("name")) for c in (d.get("credits") or {}).get("by", []) if c.get("name")]
                if by:
                    art["byline"] = ", ".join(by)
                art["date"] = d.get("display_date") or d.get("first_publish_date") or art["date"]
                art["method"] = "arc"
        except ValueError:
            pass
    for blk in re.findall(r'<script[^>]+application/ld\+json[^>]*>(.*?)</script>', s, re.S):   # JSON-LD
        try:
            d = json.loads(blk.strip())
        except ValueError:
            continue
        items = d if isinstance(d, list) else d.get("@graph", [d]) if isinstance(d, dict) else []
        for it in items:
            if not (isinstance(it, dict) and "Article" in str(it.get("@type", ""))):
                continue
            pub = it.get("publisher")
            if isinstance(pub, dict) and pub.get("name") and not art["source"]:
                art["source"] = pub["name"]
            art["date"] = art["date"] or it.get("datePublished") or ""
            art["description"] = art["description"] or strip_tags(it.get("description") or "")
            a = it.get("author")
            names = [x.get("name", "") for x in (a if isinstance(a, list) else [a]) if isinstance(x, dict)]
            if any(names) and not art["byline"]:
                art["byline"] = ", ".join(n for n in names if n)
            if it.get("articleBody") and not art["body"]:
                art["body"] = strip_tags(it["articleBody"])
                art["title"] = it.get("headline") or art["title"]
                art["method"] = "jsonld"
    if not art["body"]:
        scope = (re.search(r"<article[^>]*>(.*?)</article>", s, re.S) or [None, s])[1]
        paras = [strip_tags(p) for p in re.findall(r"<p[^>]*>(.*?)</p>", scope, re.S)]
        art["body"] = "\n".join(p for p in paras if len(p) > 40 and not re.match(r"^(Share|Save|Advertisement|Related)\b", p))
        art["method"] = "paragraphs"
    art["body"] = art["body"][:20000]
    art["lang"] = detect_lang(art["title"] + " " + art["body"])
    return art


def cmd_fetch(job):
    inp = job.data["input"]
    if inp.get("kind") == "text":
        text = inp.get("text", "").strip()
        if len(text) < 80:
            raise EngineError("TEXT_TOO_SHORT")
        lines = [l.strip() for l in text.splitlines() if l.strip()]
        art = {"url": "", "title": lines[0][:120], "subtitle": "", "description": "", "source": "", "date": "",
               "byline": "", "body": text[:20000], "method": "text", "lang": detect_lang(text)}
    else:
        url = inp.get("url", "").strip()
        code, b = http_get(url, UA_BROWSER, timeout=30)
        if code >= 300:
            raise EngineError("FETCH_FAILED")
        art = extract_article(url, b.decode("utf-8", "replace"))
        if len(art["body"]) < 200:
            raise EngineError("NO_TEXT")
    save(job.p("article.json"), art)
    job.data.update(stage="fetched", lang=art["lang"])
    job.save()
    out({"ok": True, "title": art["title"], "chars": len(art["body"]), "method": art["method"], "lang": art["lang"],
         "language": LANG[art["lang"]]["name"], "style": LANG[art["lang"]]["style"],
         "sourceLabel": LANG[art["lang"]]["source"], "budget": budget(job.data.get("target", 55), art["lang"]),
         "captionChars": LANG[art["lang"]]["cap"], "headlineChars": LANG[art["lang"]]["head"]})


