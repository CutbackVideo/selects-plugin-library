def strip_tags(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", s or ""))).strip()


def norm_words(text):
    return [re.sub(r"[.,!?'\"“”‘’·…()。、，！？「」]", "", w) for w in text.split()]


# ---- Language ----------------------------------------------------------------------------------
def detect_lang(text):
    t = text[:5000]
    if len(re.findall(r"[\uac00-\ud7a3]", t)) > 20:
        return "ko"
    if len(re.findall(r"[぀-ヿ]", t)) > 20:
        return "ja"
    if len(re.findall(r"[一-鿿]", t)) > 40:
        return "zh"
    words = re.findall(r"[a-zà-ÿğüşıöç]+", t.lower())
    scores = {k: sum(1 for w in words if w in set(v)) for k, v in STOPWORDS.items()}
    best = max(scores, key=scores.get)
    return best if scores[best] > 3 else "en"


def word_weight(w, lang):
    """Speech units of one written word: characters for CJK, a syllable estimate for Latin."""
    digits = len(re.findall(r"\d", w))
    if LANG[lang]["cjk"]:
        cjk = len(re.findall(r"[\uac00-\ud7a3぀-ヿ一-鿿]", w))
        latin = re.findall(r"[A-Za-z]+", w)
        return max(0.5, cjk + digits * 1.5 + sum(len(x) * (1.5 if x.isupper() else 0.5) for x in latin))
    groups = len(re.findall(r"[aeiouyàáâäãåèéêëìíîïòóôöõùúûüıAEIOUY]+", w))
    caps = len(w) if re.fullmatch(r"[A-Z]{2,5}", re.sub(r"\W", "", w)) else 0   # acronyms read letter by letter
    return max(1.0, groups, caps) + digits * 1.2


def speech_seconds(text, lang):
    return sum(word_weight(w, lang) for w in text.split()) / LANG[lang]["rate"]


def budget(target, lang):
    nb = max(3, min(10, int(round(target / 8.0))))
    speak = max(8.0, target - END_HOLD - nb * (LEAD + TAIL))
    L = LANG[lang]
    if L["cjk"]:
        return {"beats": nb, "unit": "characters" if lang != "ko" else "syllables", "count": int(round(speak * L["rate"]))}
    return {"beats": nb, "unit": "words", "count": int(round(speak * L["wps"]))}


# ---- Job folder ----------------------------------------------------------------------------------
class Job:
    def __init__(self, path):
        self.dir = path
        self.path = os.path.join(path, "job.json")
        self.data = load(self.path)
        if not self.data:
            raise EngineError("job.json missing in %s" % path)
        self.id = self.data["id"]

    def p(self, *parts):
        d = os.path.join(self.dir, *parts[:-1])
        os.makedirs(d, exist_ok=True)
        return os.path.join(d, parts[-1])

    def save(self):
        self.data["updated"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        save(self.path, self.data)

    def plan(self):
        p = load(os.path.join(self.dir, "plan.json"))
        if not p:
            raise EngineError("plan.json missing")
        return p

    def gen(self):
        return load(os.path.join(self.dir, "gen.json"), {}) or {}

    def file(self, key):
        g = self.gen().get(key) or {}
        path = g.get("path")
        return path if path and os.path.exists(path) else None


