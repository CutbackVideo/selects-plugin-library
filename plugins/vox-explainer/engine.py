def headline_size(text):
    units = sum(1.0 if re.match(r"[぀-ヿ\u3131-\ud7a3一-鿿]", ch) else 0.3 if ch == " " else 0.62 for ch in text)
    return int(min(100, 860 / max(units, 1)))


def credit_line(portraits, lang):
    groups = {}
    for p in portraits.values():
        if p.get("ok"):
            lic = LANG[lang]["pd"] if re.search(r"public domain|^pd|cc0", p["license"], re.I) else p["license"]
            groups.setdefault(lic, set()).add(p.get("artist") or "")
    if not groups:
        return ""
    parts = ["%s(%s)" % (", ".join(sorted(a for a in v if a)), lic) if any(v) else lic for lic, v in groups.items()]
    return "%s · Wikimedia Commons: %s" % (LANG[lang]["photos"], "; ".join(parts))


