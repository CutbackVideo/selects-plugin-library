// Installed scripts are self-contained. Reuse the canonical SDK-safe reader
// when generating this operation, without an installed repository import.
import {readFileSync,writeFileSync} from 'node:fs';
const source=readFileSync(new URL('../../shared/bundled-assets.js',import.meta.url),'utf8');
const names=['bundledAssetIssue','readBundledAssetResource'];
const functions=await import('data:text/javascript;base64,'+Buffer.from(source+'\nexport {'+names.join(',')+'};').toString('base64'));
const template=readFileSync(new URL('./dev/ensure-audio.template.js',import.meta.url),'utf8');
const generated='// Generated by mini-vlog/operation-builder.mjs from the shared asset reader and local operation template.\n'+names.map(name=>functions[name].toString()).join('\n')+'\n'+template;
const target=new URL('./scripts/ensure-audio.js',import.meta.url);
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==generated){console.error('Out-of-date Mini Vlog Audio operation');process.exitCode=1;}
}else writeFileSync(target,generated);

// Program matching shares the existing Image program owner with photo templates.
const authoringSource=readFileSync(new URL('../../shared/native-image-authoring.js',import.meta.url),'utf8');
const {imageProgramsFeature}=await import('data:text/javascript;base64,'+Buffer.from(authoringSource+'\nexport {imageProgramsFeature};').toString('base64'));
const decorateTemplate=readFileSync(new URL('./dev/decorate.template.js',import.meta.url),'utf8');
const decoration='// Generated by mini-vlog/operation-builder.mjs from shared program verification and the local decoration template.\n'+imageProgramsFeature.toString()+'\n'+decorateTemplate;
const decorateTarget=new URL('./scripts/decorate.js',import.meta.url);
if(process.argv.includes('--check')){
 if(readFileSync(decorateTarget,'utf8')!==decoration){console.error('Out-of-date Mini Vlog decoration operation');process.exitCode=1;}
}else writeFileSync(decorateTarget,decoration);
