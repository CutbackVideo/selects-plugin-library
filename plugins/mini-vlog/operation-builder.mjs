// Installed scripts are self-contained. Reuse the canonical SDK-safe reader
// when generating this operation, without an installed repository import.
import {readFileSync,writeFileSync} from 'node:fs';
const source=readFileSync(new URL('../../shared/bundled-assets.js',import.meta.url),'utf8');
const names=['bundledAssetIssue','readBundledAssetResource'];
const functions=await import('data:text/javascript;base64,'+Buffer.from(source+'\nexport {'+names.join(',')+'};').toString('base64'));
const template=readFileSync(new URL('./dev/ensure-audio.template.js',import.meta.url),'utf8');
const generated='// Generated by mini-vlog/operation-builder.mjs from the shared asset reader and local operation template.\n'+names.map(name=>functions[name].toString()).join('\n')+'\n'+template;
const target=new URL('./scripts/ensure-audio.js',import.meta.url);
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==generated){console.error('Out-of-date Mini Vlog Audio operation');process.exitCode=1;}
}else writeFileSync(target,generated);

