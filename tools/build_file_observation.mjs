// Rebuild a self-contained, SDK-safe owner with the existing vetted SHA-256.
// Dependencies are build-only; the shipped function never imports at runtime.
import {readFileSync,writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dependencyRoot=process.env.SELECTS_DEV_REPO;
if(!dependencyRoot)throw Error('Set SELECTS_DEV_REPO to an existing Cutback Client checkout with esbuild and @noble/hashes 2.2.0 installed.');
const require=createRequire(path.join(dependencyRoot,'package.json'));
const {build}=require('esbuild');
const ts=require('typescript');
const nobleEntry=require.resolve('@noble/hashes/sha2.js');
const nobleRoot=path.dirname(nobleEntry),metadata=JSON.parse(readFileSync(path.join(nobleRoot,'package.json'),'utf8'));
if(metadata.version!=='2.2.0')throw Error('Expected the reviewed @noble/hashes version 2.2.0.');
const license=readFileSync(path.join(nobleRoot,'LICENSE'),'utf8').trim();
const source=readFileSync(path.join(root,'shared/file-observation.source.js'),'utf8');
const result=await build({stdin:{contents:'export {sha256} from '+JSON.stringify(nobleEntry)+';',resolveDir:root,sourcefile:'file-observation-hash.js',loader:'js'},bundle:true,format:'iife',globalName:'__templateFileHash',platform:'neutral',target:'es2020',minify:true,treeShaking:true,legalComments:'none',write:false});
// The SDK accepts TypeScript source, while this owner must also be plain JS.
// TypeScript rejects the vendor's dynamic class/function properties in a .ts
// script. Identity calls loosen only vendor expressions, without directives,
// eval, altered receiver binding or changes to the observation/SDK-call code.
const vendor=ts.createSourceFile('hash.js',result.outputFiles[0].text,ts.ScriptTarget.ES2020,true,ts.ScriptKind.JS);
const transformed=ts.transform(vendor,[context=>{
 const f=context.factory,identity=expression=>f.createCallExpression(f.createIdentifier('__templateHashAny'),undefined,[expression]);
 const visit=node=>{
  if(node.kind===ts.SyntaxKind.ThisKeyword)return identity(node);
  const next=ts.visitEachChild(node,visit,context);
  if(ts.isPropertyAccessExpression(next)&&next.expression.kind!==ts.SyntaxKind.SuperKeyword)return f.updatePropertyAccessExpression(next,identity(next.expression),next.name);
  if(ts.isElementAccessExpression(next)&&next.expression.kind!==ts.SyntaxKind.SuperKeyword)return f.updateElementAccessExpression(next,identity(next.expression),next.argumentExpression);
  if(ts.isCallExpression(next)&&!ts.isPropertyAccessExpression(next.expression)&&!ts.isElementAccessExpression(next.expression)&&next.expression.kind!==ts.SyntaxKind.SuperKeyword)return f.updateCallExpression(next,identity(next.expression),next.typeArguments,next.arguments);
  if(ts.isNewExpression(next))return f.updateNewExpression(next,identity(next.expression),next.typeArguments,next.arguments);
  if(ts.isExpressionWithTypeArguments(next))return f.updateExpressionWithTypeArguments(next,identity(next.expression),next.typeArguments);
  return next;
 };return node=>ts.visitNode(node,visit);
}]);
const code='const __templateHashAny=value=>value;\n'+ts.createPrinter({removeComments:true}).printFile(transformed.transformed[0]).trim();
transformed.dispose();
// SHA's compression method is named process(); only a host process global is forbidden.
if(/\brequire\s*\(|\bimport\s|(?<![.\w])process\s*[.\[]|\bglobalThis\b|\beval\s*\(|new Function/.test(code))throw Error('The fingerprint bundle contains a forbidden runtime dependency.');
const signature='export async function fingerprintTemplateFile(files,path,check=()=>{}) {';
if(source.split(signature).length!==2||!source.trimEnd().endsWith('}'))throw Error('Unexpected file observation source signature.');
const body=source.split(signature)[1].trimEnd().slice(0,-1).replace('sha256.create()','__templateFileHash.sha256.create()');
const generated='// Generated by tools/build_file_observation.mjs; edit file-observation.source.js.\n'+
 'export async function fingerprintTemplateFile(files,path,check=()=>{}) {\n'+
 '/* @noble/hashes 2.2.0; license retained inside serialized SDK copies.\n'+license+'\n*/\n'+
 code+'\n'+body+'}\n';
const target=path.join(root,'shared/file-observation.js'),notice=path.join(root,'shared/file-observation.LICENSE');
const check=process.argv.includes('--check');
if(process.argv.slice(2).some(arg=>arg!=='--check'))throw Error('Usage: node tools/build_file_observation.mjs [--check]');
for(const [file,content] of [[target,generated],[notice,license+'\n']]){
 if(check){if(readFileSync(file,'utf8')!==content)throw Error('Out-of-date fingerprint build: '+path.relative(root,file));}
 else writeFileSync(file,content);
}
console.log(check?'Checked SDK-free file observation owner.':'Built SDK-free file observation owner.');
