// Bundle the portable shader factories into self-contained authoring functions.
// Panels are installed alone; run_script requests cannot import repository files.
import {readFileSync,writeFileSync,mkdirSync,readdirSync,existsSync} from 'node:fs';
import {createRequire} from 'node:module';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';

import {syncShaderFactories} from './sync-shader-factories.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(import.meta.url);
const esbuild=require(process.env.ESBUILD||'esbuild');
const ts=createRequire(require.resolve(process.env.ESBUILD||'esbuild'))('typescript');
const registry=JSON.parse(readFileSync(join(root,'shared/shader-effects/plugins.json'),'utf8'));
const directory=join(root,'shared/shader-effects/generated');
mkdirSync(directory,{recursive:true});
for(const [id,entries] of Object.entries(registry)) {
  const imports=[],cases=[];
  for(const [kind,[module,fn,arg]] of Object.entries(entries)) {
    const name=`factory${imports.length}`;
    imports.push(`import {${fn} as ${name}} from './${module}.mjs';`);
    const args=fn==='grade'?`${JSON.stringify(arg)},data`:fn==='polaroid'?`data,${arg===true}`:fn==='fourPhotoReveal'?'data,context.fps||30':fn==='photoMotion'?'data,context':'data';
    cases.push(`case ${JSON.stringify(kind)}: shader=${name}(${args});break;`);
  }
  const source=imports.join('\n')+`
    export function options(kind,input,context=null) {
      context=context||{};
      if ('tsxCode' in input) throw Error('A WGSL effect cannot carry legacy TSX');
      const data={...Object.fromEntries((input.editableParameters||[]).map(control=>[control.key,control.defaultValue])),...input.parameters};let shader;
      switch(kind){${cases.join('\n')}default:throw Error('Unknown ${id} effect: '+kind);}
      return {...input,parameters:data,shader};
    }`;
  let bundle=esbuild.buildSync({stdin:{contents:source,resolveDir:join(root,'shared/shader-effects'),sourcefile:id+'.mjs',loader:'js'},bundle:true,write:false,format:'esm',platform:'neutral',target:'es2022',minify:false,legalComments:'none'}).outputFiles[0].text;
  bundle=bundle.replace(/export\s*\{\s*options\s*\};?\s*$/, '');
  const expression=`(()=>{${bundle}\nreturn options;})()`;
  const generated=join(directory,id+'.mjs');
  function sync(folder){for(const entry of readdirSync(folder,{withFileTypes:true})){
    if(entry.isDirectory()){if(!['tests','node_modules','.git'].includes(entry.name))sync(join(folder,entry.name));continue;}
    if(!/\.(?:[cm]?js|tsx?)$/.test(entry.name))continue;
    const file=join(folder,entry.name),old=readFileSync(file,'utf8');
    const text=syncShaderFactories(old,expression,ts);
    if(text!==old)writeFileSync(file,text);
  }}
  sync(join(root,'plugins',id));
  writeFileSync(generated,`// Generated by tools/build-plugin-shaders.mjs.\nexport const PLUGIN_SHADER_OPTIONS=${JSON.stringify(expression)};\n`);
}
console.log(`Built ${Object.keys(registry).length} portable plugin effect factories.`);
